using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;
using LauncherCatalog.Models;

namespace LauncherCatalog.Services.Ai;

/// <summary>
/// Placeholder backend used while the real (Playwright-driven Gemini) backend is built in a later
/// stage. It returns schema-valid, clearly-labelled responses so the end-to-end HTTP path, request
/// queue, auth, and the Chrome extension can be exercised without any browser automation.
/// </summary>
public sealed class StubAiBackend : IAiBackend
{
    public IReadOnlyList<string> Providers { get; } = new[] { "stub" };

    public bool IsReady => true;

    public Task<AiAnalyzeResult> AnalyzeAsync(string prompt, CancellationToken cancellationToken)
    {
        var result = new AiAnalyzeResult(
            Category: "fyi",
            Summary: "Stub response from the WorkSync AI Bridge. The real Gemini backend is not wired up yet.",
            DetectedEmailLanguage: "en",
            UserIsDirectlyAddressed: false,
            ReplyOptions: new[]
            {
                new AiReplyOption("acknowledge", "Acknowledge", "Send a short acknowledgement."),
                new AiReplyOption("decline", "Politely decline", "Decline the request politely."),
                new AiReplyOption("more_info", "Ask for details", "Ask the sender for more information.")
            },
            Confidence: 0.0,
            Reasoning: "Generated by StubAiBackend; this is not a real analysis.");

        return Task.FromResult(result);
    }

    public Task<AiDraftResult> DraftAsync(string prompt, CancellationToken cancellationToken)
    {
        var result = new AiDraftResult(
            DraftLanguage: "en",
            Subject: "Re: (stub)",
            Body: "This is a stub draft from the WorkSync AI Bridge. The real Gemini backend is not wired up yet.",
            Tone: "neutral",
            NotesForUser: "Generated by StubAiBackend; replace with a real draft once the backend is implemented.");

        return Task.FromResult(result);
    }
}
